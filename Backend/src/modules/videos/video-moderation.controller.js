export async function handleGetSubtitle(req, res) {
  try {
    const result = await getSubtitleInternal({ params: req.params, query: req.query });
    for (const [name, value] of Object.entries(result.headers)) res.setHeader(name, value);
    return res.status(result.status)[result.format](result.body);
  } catch (error) {
    return res
      .status(error.status || 500)
      .json(error.body || { message: error.message || 'Internal server error' });
  }
}

