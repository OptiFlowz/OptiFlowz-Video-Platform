const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const React = require('react');
const { act } = React;
const { JSDOM } = require('jsdom');

test('shared toast survives page changes, replaces repeated messages and cleans up its timer', async t => {
  const dom = new JSDOM('<div id="root"></div>');
  const previous = new Map(['window', 'document', 'IS_REACT_ACT_ENVIRONMENT'].map(key => [key, Object.getOwnPropertyDescriptor(globalThis, key)]));
  Object.assign(globalThis, { window: dom.window, document: dom.window.document, IS_REACT_ACT_ENVIRONMENT: true });
  const { createRoot } = require('react-dom/client');
  const timers = new Map(); let nextId = 0;
  const frames = new Map();
  window.requestAnimationFrame = callback => { frames.set(++nextId, callback); return nextId; };
  window.cancelAnimationFrame = id => frames.delete(id);
  window.setTimeout = (callback, delay) => { timers.set(++nextId, { callback, delay }); return nextId; };
  window.clearTimeout = id => timers.delete(id);
  const code = ts.transpileModule(fs.readFileSync('app/components/toast/Toast.tsx', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX } }).outputText;
  const mod = { exports: {} };
  new Function('require', 'module', 'exports', code)(name => name === '~/constants' ? { CheckSVG: '✓' } : name.endsWith('.css') ? { __esModule: true, default: new Proxy({}, { get: (_, key) => String(key) }) } : require(name), mod, mod.exports);
  const { ToastHost, showToast, startToast } = mod.exports, root = createRoot(document.getElementById('root'));
  t.after(async () => {
    await act(async () => root.unmount()); dom.window.close();
    for (const [key, value] of previous) { if (value) Object.defineProperty(globalThis, key, value); else delete globalThis[key]; }
  });
  const render = page => act(async () => root.render(React.createElement(React.Fragment, null, React.createElement(ToastHost), React.createElement('main', null, page))));
  await render('Edit question');
  const host = document.querySelector('[role="status"]');
  assert.equal(host.parentElement, document.body);
  await act(async () => showToast('Changes saved.'));
  assert.equal(host.textContent, '✓Changes saved.');
  await render('Question bank');
  assert.equal(host.textContent, '✓Changes saved.');
  await act(async () => showToast('Changes saved.'));
  assert.equal(timers.size, 1, 'repeated saves replace the timeout instead of stacking toasts');
  assert.equal(document.querySelectorAll('.toast').length, 1);
  const fire = async delay => act(async () => { for (const [id, timer] of [...timers]) if (timer.delay === delay) { timers.delete(id); timer.callback(); } });
  const frame = async () => act(async () => { const callbacks = [...frames.values()]; frames.clear(); callbacks.forEach(callback => callback()); });
  const exit = async () => act(async () => {
    const event = new window.Event('transitionend', { bubbles: true });
    Object.defineProperty(event, 'propertyName', { value: 'transform' });
    document.querySelector('.toast').dispatchEvent(event);
  });
  await frame(); await frame();
  assert.equal(document.querySelector('.toast').classList.contains('visible'), true);
  await fire(2000);
  assert.equal(document.querySelector('.toast').dataset.exiting, 'true', 'retain the notification throughout its upward exit');
  assert.equal(document.querySelector('.toast').classList.contains('visible'), false);
  await exit();
  assert.equal(host.textContent, '');
  let pending;
  await act(async () => { pending = startToast('Saving changes…'); });
  const notification = document.querySelector('.toast');
  assert.ok(notification.querySelector('.uploadSpinner'));
  assert.equal(notification.textContent, 'Saving changes…');
  assert.equal(timers.size, 0, 'loading stays visible for arbitrarily long requests');
  await render('Rules');
  assert.equal(document.querySelector('.toast'), notification, 'navigation does not interrupt loading');
  await act(async () => pending.success('Changes saved.'));
  assert.equal(document.querySelector('.toast'), notification, 'success updates the existing shell');
  assert.equal(notification.querySelector('.leaving').getAttribute('aria-hidden'), 'true');
  assert.equal(notification.querySelector('.entering').textContent, '✓Changes saved.');
  assert.ok(notification.querySelector('.leaving .uploadSpinner'), 'loading content remains during the cross-fade');
  await fire(180);
  assert.equal(notification.querySelector('.leaving'), null);
  assert.equal(notification.querySelector('.uploadSpinner'), null);
  assert.equal(notification.textContent, '✓Changes saved.');
  await fire(2000);
  assert.ok(host.textContent.includes('Changes saved.'), 'expiry starts the exit instead of removing the shell');
  await fire(280);
  assert.equal(host.textContent, '');
  let older, newer;
  await act(async () => { older = startToast('Older action'); newer = startToast('New action'); older.success('Old result'); older.dismiss(); });
  assert.equal(host.querySelector('.entering').textContent, 'New action', 'stale actions never replace or dismiss newer notifications');
  await fire(180);
  await act(async () => newer.dismiss());
  assert.equal(document.querySelector('.toast').dataset.exiting, 'true');
  await exit();
  assert.equal(host.textContent, '', 'failed or cancelled actions can clear their loading state');
  assert.equal(timers.size, 0);
  await act(async () => { older = startToast('Saving'); showToast('Different action completed'); older.success('Late result'); });
  assert.equal(host.querySelector('.entering').textContent, '✓Different action completed');
  await fire(180);
  await fire(2000);
  await act(async () => showToast('Reopened during exit'));
  await fire(280);
  assert.equal(document.querySelector('.toast').dataset.exiting, 'false', 'a stale exit cannot remove a new notification');
  assert.equal(host.querySelector('.entering').textContent, '✓Reopened during exit');
  await act(async () => showToast('Saved again'));
  await act(async () => root.unmount());
  assert.equal(timers.size, 0);
  assert.equal(frames.size, 0, 'entrance frames are cancelled on unmount');
  await act(async () => showToast('After unmount'));
  assert.equal(timers.size, 0, 'listener is removed on unmount');
});
